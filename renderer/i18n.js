  function interpolate(text, vars) {
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (_, key) => (vars[key] == null ? '' : String(vars[key])));
  }

  function t(locale, key, vars) {
    const table = STRINGS[locale] || STRINGS.ru;
    const raw = table[key] || STRINGS.en[key] || STRINGS.ru[key] || key;
    return interpolate(raw, vars);
  }

  function applyDom(locale) {
    if (typeof document === 'undefined') return;
    document.documentElement.lang = locale === 'en' ? 'en' : 'ru';
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(locale, el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-tip]').forEach((el) => {
      el.dataset.tip = t(locale, el.getAttribute('data-i18n-tip'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      const text = t(locale, el.getAttribute('data-i18n-title'));
      el.title = text;
      el.setAttribute('aria-label', text);
    });
  }

  return { STRINGS, t, applyDom };
